/** 返回 flag-icons 的 CSS 类名，如 "fi fi-kr"；未知代码返回 null */
export function flagClass(code: string): string | null {
  const upper = code.toUpperCase()
  // 中国台北使用奥运会会旗（梅花标志），样式在 styles.css 里的 .fi-tpe
  if (upper === 'TPE') return 'fi fi-tpe'
  const c = COUNTRIES[upper]
  return c ? `fi fi-${c.iso}` : null
}

